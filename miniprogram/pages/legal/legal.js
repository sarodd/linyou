Page({
  data: {
    title: '',
    intro: '',
    sections: [],
    updatedAt: '',
    contact: '',
    notFound: false
  },
  onLoad(options) {
    const type = options && options.type === 'terms' ? 'terms' : 'privacy'
    const doc = DOCS[type]
    if (!doc) {
      this.setData({ notFound: true })
      return
    }
    wx.setNavigationBarTitle({ title: doc.title })
    this.setData({
      title: doc.title,
      intro: doc.intro,
      sections: doc.sections,
      updatedAt: OPERATOR.updatedAt,
      contact: OPERATOR.contactEmail || ''
    })
  },
  copyContact() {
    if (!this.data.contact) return
    wx.setClipboardData({ data: this.data.contact })
  }
})
